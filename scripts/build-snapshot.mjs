import { writeFileSync } from 'node:fs'
import {
  controlFromMarket,
  governorControlFromEvent,
  houseFromEvents,
  parseEarlyCsv,
  racesFromEvents,
} from '../src/lib/parse.ts'
import { houseExpected, senateCall } from '../src/lib/derive.ts'

const headers = { 'User-Agent': 'midterm-board/1.0', Accept: 'application/json,text/csv,*/*' }

async function getJson(url) {
  const response = await fetch(url, { headers })
  if (!response.ok) throw new Error(`${response.status} ${url}`)
  return response.json()
}

async function getText(url) {
  const response = await fetch(url, { headers })
  if (!response.ok) throw new Error(`${response.status} ${url}`)
  return response.text()
}

async function search(query, pages) {
  const events = []
  for (let page = 1; page <= pages; page += 1) {
    const url = new URL('https://gamma-api.polymarket.com/public-search')
    url.searchParams.set('q', query)
    url.searchParams.set('page', String(page))
    url.searchParams.set('limit_per_type', '50')
    const payload = await getJson(url)
    events.push(...(payload.events ?? []))
    if (!payload.pagination?.hasMore) break
  }
  return events
}

const [senateEvents, governorEvents, houseEvents, senateMarket, houseMarket, governorEvent, earlyCsv] =
  await Promise.all([
    search('senate election winner', 4),
    search('governor election winner', 4),
    search('house election winner', 14),
    getJson('https://gamma-api.polymarket.com/markets/slug/will-the-democratic-party-control-the-senate-after-the-2026-midterm-elections'),
    getJson('https://gamma-api.polymarket.com/markets/slug/will-the-democratic-party-control-the-house-after-the-2026-midterm-elections'),
    getJson('https://gamma-api.polymarket.com/events?slug=which-party-will-hold-more-governorships-after-the-midterms'),
    getText('https://election.lab.ufl.edu/data-downloads/earlyvote/2026/US.csv'),
  ])

const senateDem = controlFromMarket(senateMarket) ?? 0
const houseDem = controlFromMarket(houseMarket) ?? 0
const governor = governorControlFromEvent(Array.isArray(governorEvent) ? governorEvent[0] : governorEvent) ?? {
  dem: 0,
  rep: 0,
  tie: 0,
}

const snapshot = {
  fetchedAt: new Date().toISOString(),
  live: false,
  senateControl: { dem: senateDem, rep: Math.max(0, 1 - senateDem), tie: 0 },
  houseControl: { dem: houseDem, rep: Math.max(0, 1 - houseDem), tie: 0 },
  governorControl: governor,
  senateRaces: racesFromEvents(senateEvents, 'senate'),
  governorRaces: racesFromEvents(governorEvents, 'governor'),
  houseRaces: houseFromEvents(houseEvents),
  early: parseEarlyCsv(earlyCsv),
}

const calls = senateCall(snapshot.senateRaces)
const house = houseExpected(snapshot.houseRaces)
console.log('senate races', snapshot.senateRaces.length, 'call', calls)
console.log('governor races', snapshot.governorRaces.length, 'control', governor)
console.log('house races', snapshot.houseRaces.length, 'expected', house)
console.log('early rows', snapshot.early.length, 'voted', snapshot.early.reduce((sum, row) => sum + row.voted, 0))
console.log('control', senateDem, houseDem)

const file = `/* Generated by scripts/build-snapshot.mjs. Refresh with: node --experimental-strip-types scripts/build-snapshot.mjs */
import type { Snapshot } from '../lib/types.ts'

const fallback: Snapshot = ${JSON.stringify(snapshot, null, 2)}

export default fallback
`

writeFileSync(new URL('../src/data/fallback.ts', import.meta.url), file)
console.log('wrote src/data/fallback.ts')
