const topo = JSON.parse(readFileSync('/tmp/geo/states-10m.json', 'utf8'))
const all = feature(topo, topo.objects.states)
const states = {
  type: 'FeatureCollection',
  features: all.features.filter((item) => FIPS[String(item.id).padStart(2, '0')]),
}

const width = 960
const height = 600
const projection = geoAlbersUsa().fitExtent(
  [
    [12, 16],
    [860, 584],
  ],
  states,
)
const path = geoPath(projection)
const rows = []

for (const item of states.features) {
  const fips = String(item.id).padStart(2, '0')
  const abbr = FIPS[fips]
  const d = path(item)
  if (!d || !abbr) continue
  const [cx, cy] = path.centroid(item)
  rows.push({
    abbr,
    d,
    cx: Number(cx.toFixed(1)),
    cy: Number(cy.toFixed(1)),
  })
}

rows.sort((a, b) => a.abbr.localeCompare(b.abbr))

const body = `/* Generated by scripts/build-map.mjs from us-atlas states-10m. */
export const MAP_WIDTH = ${width}
export const MAP_HEIGHT = ${height}

export type StatePath = {
  abbr: string
  d: string
  cx: number
  cy: number
}

export const STATE_PATHS: StatePath[] = ${JSON.stringify(rows)}
`

writeFileSync(new URL('../src/geo/statePaths.ts', import.meta.url), body)
